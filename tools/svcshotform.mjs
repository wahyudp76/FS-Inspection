import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require('/home/user/tools/node_modules/playwright-core')
const b = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1117/chrome-linux/chrome', args: ['--no-sandbox'] })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
await ctx.addInitScript(() => { try { localStorage.setItem('fsi:endpoint', 'http://127.0.0.1:8112/exec') } catch (e) {} })
const p = await ctx.newPage()
await p.goto('http://127.0.0.1:8099/#/service', { waitUntil: 'networkidle' })
await p.waitForTimeout(2000)
await p.locator('button:has-text("Catat Service")').first().click()
await p.waitForTimeout(600)
await p.fill('[role="dialog"] input[placeholder*="Cari kode"]', 'SPC0157')
await p.waitForTimeout(300)
await p.click('[role="option"]:has-text("SPC0157")')
await p.waitForTimeout(400)
await p.fill('[role="dialog"] input[type="date"]', '2026-10-22')
await p.waitForTimeout(300)
await p.evaluate(() => document.querySelector('[role="dialog"] .overflow-y-auto').scrollTo(0, 260))
await p.waitForTimeout(400)
await p.screenshot({ path: '/home/user/tools/svc-form-minggu.png' })
await b.close()
